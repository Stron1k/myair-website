/* =========================
   LANGUAGE SWITCHER
========================= */

function changeLanguage(language) {

    const selectedLanguage = translations[language];

    if (!selectedLanguage) {
        return;
    }


    document.documentElement.lang = language;

    document.title = selectedLanguage.pageTitle;


    const textElements =
        document.querySelectorAll("[data-i18n]");


    textElements.forEach((element) => {

        const key = element.dataset.i18n;

        if (selectedLanguage[key] !== undefined) {

            element.innerHTML =
                selectedLanguage[key];

        }

    });


    const altElements =
        document.querySelectorAll("[data-i18n-alt]");


    altElements.forEach((element) => {

        const key = element.dataset.i18nAlt;

        if (selectedLanguage[key] !== undefined) {

            element.alt =
                selectedLanguage[key];

        }

    });


    const languageButtons =
        document.querySelectorAll(".language");


    languageButtons.forEach((button) => {

        if (button.dataset.lang === language) {

            button.classList.add("active");

        } else {

            button.classList.remove("active");

        }

    });


    updateMobileMenuLabel(language);


    localStorage.setItem(
        "myair-language",
        language
    );
}



/* =========================
   LANGUAGE BUTTONS
========================= */

const languageButtons =
    document.querySelectorAll(".language");


languageButtons.forEach((button) => {

    button.addEventListener("click", () => {

        const language =
            button.dataset.lang;

        changeLanguage(language);

    });

});



/* =========================
   MOBILE MENU
========================= */

const mobileMenuButton =
    document.getElementById("mobileMenuButton");

const mobileNavigation =
    document.getElementById("mobileNavigation");


function openMobileMenu() {

    mobileNavigation.classList.add("open");

    mobileMenuButton.classList.add("active");

    mobileMenuButton.setAttribute(
        "aria-expanded",
        "true"
    );

}


function closeMobileMenu() {

    mobileNavigation.classList.remove("open");

    mobileMenuButton.classList.remove("active");

    mobileMenuButton.setAttribute(
        "aria-expanded",
        "false"
    );

}


function toggleMobileMenu() {

    const isOpen =
        mobileNavigation.classList.contains("open");


    if (isOpen) {

        closeMobileMenu();

    } else {

        openMobileMenu();

    }

}


mobileMenuButton.addEventListener(
    "click",
    toggleMobileMenu
);



/* CLOSE MENU AFTER CLICKING LINK */

const mobileLinks =
    mobileNavigation.querySelectorAll("a");


mobileLinks.forEach((link) => {

    link.addEventListener("click", () => {

        closeMobileMenu();

    });

});



/* CLOSE MENU WITH ESC */

document.addEventListener("keydown", (event) => {

    if (event.key === "Escape") {

        closeMobileMenu();

    }

});



/* CLOSE MENU AFTER RESIZING TO DESKTOP */

window.addEventListener("resize", () => {

    if (window.innerWidth > 900) {

        closeMobileMenu();

    }

});



/* =========================
   MOBILE MENU ARIA LABEL
========================= */

function updateMobileMenuLabel(language) {

    if (language === "ru") {

        mobileMenuButton.setAttribute(
            "aria-label",
            "Открыть меню"
        );

    } else {

        mobileMenuButton.setAttribute(
            "aria-label",
            "Atvērt izvēlni"
        );

    }

}



